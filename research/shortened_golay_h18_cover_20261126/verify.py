G=[7973,8559,17118,34236,68472,133589]
H=[0]
for g in G:H += [h^g for h in H]
assert len(set(H))==64 and all(h.bit_count()%4==0 for h in H)
assert min(h.bit_count() for h in H if h)==8
C=[sum(((g>>j)&1)<<i for i,g in enumerate(G)) for j in range(18)]
CS=set(C)
assert C[-6:]==[1<<i for i in range(6)] and len(CS)==18
A=[]
def extend(f):
    if len(f)==64:
        A.append([C.index(f[x]) for x in C])
        return
    for t in C:
        if t in f:continue
        old=len(f)
        nxt=[t^x for x in f]
        if all((v in CS)==((old+i) in CS) for i,v in enumerate(nxt)):extend(f+nxt)
extend([0]); assert len(A)==2160
cl={v^h:v for v in range(1<<12) for h in H}
assert len(cl)==1<<18
def tr(p,v):return sum(1<<p[i] for i in range(18) if v>>i&1)
seen=set(); R={}
for v in range(1<<12):
    if v in seen:continue
    orb={cl[tr(p,v)] for p in A}
    assert not (seen&orb)
    seen.update(orb)
    R[v]=min((v^h).bit_count() for h in H)
