def dot(x, y):
    return sum(a*b for a,b in zip(x,y))

def mv(g, x):
    return [dot(row,x) for row in g]

def coord(h):
    return [h % 4, (h//4)%4, (h//16)%2, h//32]

def four_phase(h):
    a = coord(h)
    v = [dot(a,w) for w in zip(*GENS)]
    return mv(HAD,v)  # numerator/48 after the normalized Hadamard

def key(x):
    base = [a%48 for a in x]
    if sum((a-b)//48 for a,b in zip(x,base)) % 2:
        base[0] += 48
    return tuple(base)

def rank_mod(rows, n, p=101):
    pivots = {}
    for original in rows:
        row = [x%p for x in original]
        for j in range(n):
            a = row[j]
            if not a:
                continue
            if j not in pivots:
                inv = pow(a,p-2,p)
                pivots[j] = [x*inv%p for x in row]
                break
            other = pivots[j]
            row = [(x-a*y)%p for x,y in zip(row,other)]
    return len(pivots)

